import sys
import unittest
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import openpyxl

from itgc.ingest.base import load_table, parse_date_cell
from itgc.ingest.schemas import EMPLOYEE_MASTER_SCHEMA, UAR_SCHEMA
from itgc.ingest.classify import classify_file


class TestHeaderDetection(unittest.TestCase):
    def _write_xlsx(self, path, rows):
        wb = openpyxl.Workbook()
        ws = wb.active
        for r in rows:
            ws.append(r)
        wb.save(path)

    def test_finds_header_below_banner_rows(self):
        rows = [
            ["Some Company - Confidential Export"],
            ["Generated by Tool v9"],
            [],
            ["Emp Code", "Employee Name", "Work Email", "Department", "Job Title",
             "Reporting Manager (Email)", "Employment Status", "Date of Hire", "Termination Date"],
            ["E1", "Test Person", "test.person@x.com", "Finance", "AP Clerk", "mgr@x.com", "Active", "2020-01-01", ""],
        ]
        p = Path("/tmp/_test_emp.xlsx")
        self._write_xlsx(p, rows)
        loaded = load_table(p, EMPLOYEE_MASTER_SCHEMA)
        self.assertIsNotNone(loaded)
        self.assertEqual(loaded.header_row_index, 3)
        self.assertEqual(len(loaded.rows), 1)
        self.assertEqual(loaded.rows[0]["full_name"], "Test Person")
        self.assertEqual(loaded.rows[0]["email"], "test.person@x.com")

    def test_differently_worded_headers_still_map(self):
        # a client's own column names, never seen verbatim in our alias lists
        rows = [
            ["Personnel Number", "Staff Name", "Email Address", "Division", "Position",
             "Supervisor Email", "Emp Status", "Start Date", "Last Working Day"],
            ["P1", "Alex Doe", "alex.doe@x.com", "Ops", "Analyst", "boss@x.com", "Active", "2019-05-01", ""],
        ]
        p = Path("/tmp/_test_emp2.xlsx")
        self._write_xlsx(p, rows)
        loaded = load_table(p, EMPLOYEE_MASTER_SCHEMA)
        self.assertIsNotNone(loaded)
        self.assertEqual(loaded.rows[0]["full_name"], "Alex Doe")
        self.assertEqual(loaded.rows[0]["department"], "Ops")

    def test_no_plausible_header_returns_none(self):
        rows = [["random", "junk", "data"], ["1", "2", "3"]]
        p = Path("/tmp/_test_junk.xlsx")
        self._write_xlsx(p, rows)
        loaded = load_table(p, EMPLOYEE_MASTER_SCHEMA)
        self.assertIsNone(loaded)

    def test_classify_distinguishes_employee_master_from_uar(self):
        p1 = Path("/tmp/_test_emp3.xlsx")
        self._write_xlsx(p1, [
            ["Emp Code", "Employee Name", "Work Email", "Department", "Job Title",
             "Reporting Manager (Email)", "Employment Status", "Date of Hire", "Termination Date"],
            ["E1", "Test Person", "t@x.com", "Finance", "AP Clerk", "m@x.com", "Active", "2020-01-01", ""],
        ])
        result = classify_file(p1)
        self.assertEqual(result["evidence_type"], "employee_master")

        p2 = Path("/tmp/_test_uar3.xlsx")
        self._write_xlsx(p2, [
            ["User ID", "User Full Name", "Email Address", "Access Profile(s)", "Account Status", "Last Login"],
            ["U1", "Test Person", "t@x.com", "Sales User", "Active", "01-Jan-2026"],
        ])
        result2 = classify_file(p2)
        self.assertEqual(result2["evidence_type"], "uar_sheet")


class TestDateParsing(unittest.TestCase):
    def test_various_formats(self):
        self.assertEqual(parse_date_cell("2026-07-31"), date(2026, 7, 31))
        self.assertEqual(parse_date_cell("31-Jul-2026"), date(2026, 7, 31))
        self.assertEqual(parse_date_cell("05-Sep-2026"), date(2026, 9, 5))

    def test_blank_and_junk_are_none(self):
        self.assertIsNone(parse_date_cell(""))
        self.assertIsNone(parse_date_cell(None))
        self.assertIsNone(parse_date_cell("N/A"))


if __name__ == "__main__":
    unittest.main()
