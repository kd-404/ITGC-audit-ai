"""AI Gateway: the only place in the codebase that calls an LLM.

Guardrails, per the project's own non-negotiable principle:
  - the LLM NEVER sets or changes finding_type, severity, or any evidence
    citation - those are already final by the time a Finding reaches here.
  - it only fills in `narrative`: a human-readable explanation, written for
    an audit workpaper, from the structured finding it's given.
  - on timeout, unreachable server, or malformed output, a deterministic
    template is used instead - narrative generation never blocks the pipeline
    and never fails the run.
"""
from __future__ import annotations

from ..models import Finding
from .ollama_client import OllamaClient, OllamaUnavailable

SYSTEM_PROMPT = (
    "You are an ITGC audit assistant writing workpaper narratives. You will be given a single, "
    "already-determined audit finding (type, severity, condition, criteria, cause, effect, "
    "recommendation, evidence citations) as JSON. "
    "Write ONLY a short, professional narrative paragraph (3-5 sentences) explaining the finding to "
    "a reviewing partner, in the voice of an IT auditor. "
    "Do not invent any fact, name, date, or system not present in the input. Do not change the "
    "severity or the conclusion. Respond as JSON: {\"narrative\": \"...\"}."
)

CORRELATION_SYSTEM_PROMPT = (
    "You are an ITGC audit assistant. You will be given a JSON list of two or more already-determined, "
    "independent audit findings that all concern the SAME person or account. Each finding's type, "
    "severity, and conclusion are already final - do not change or re-derive any of them, and do not "
    "invent any fact, name, date, or system not present in the input. "
    "Write ONLY a short paragraph (3-6 sentences), in the voice of an IT auditor addressing a reviewing "
    "partner, explaining why the SAME subject being flagged by this many independent controls is itself "
    "meaningful - i.e. what the combination suggests about this account/person's overall risk posture "
    "that no single finding shows on its own. Respond as JSON: {\"narrative\": \"...\"}."
)


def _fallback_narrative(f: Finding) -> str:
    return (
        f"{f.severity.value} finding ({f.finding_type.value}) in {f.system} concerning "
        f"{f.subject_person or 'an unidentified account'}. {f.condition} This does not meet the "
        f"control criteria: {f.criteria} Likely cause: {f.cause} Risk: {f.effect} "
        f"Recommended action: {f.recommendation} "
        f"(Narrative generated by deterministic fallback template - LLM unavailable or unreachable.)"
    )


def fallback_correlation_narrative(subject: str, findings: list[Finding]) -> str:
    types = sorted({f.finding_type.value for f in findings})
    domains = sorted({f.system for f in findings})
    return (
        f"{subject} is flagged by {len(findings)} independent finding(s) across this engagement "
        f"({', '.join(types)}), spanning {', '.join(domains)}. Multiple independently-derived controls "
        f"agreeing on the same subject increases confidence that this represents a genuine, not "
        f"incidental, control gap and should be prioritized for review accordingly, rather than treated "
        f"as {len(findings)} unrelated items. "
        f"(Narrative generated by deterministic fallback template - LLM unavailable or unreachable.)"
    )


class AIGateway:
    def __init__(self, client: OllamaClient | None = None):
        self.client = client or OllamaClient()
        self._reachable: bool | None = None

    def available(self) -> bool:
        if self._reachable is None:
            self._reachable = self.client.is_reachable()
        return self._reachable

    def narrate(self, finding: Finding) -> str:
        if not self.available():
            return _fallback_narrative(finding)
        payload = {
            "finding_type": finding.finding_type.value,
            "severity": finding.severity.value,
            "system": finding.system,
            "subject_person": finding.subject_person,
            "condition": finding.condition,
            "criteria": finding.criteria,
            "cause": finding.cause,
            "effect": finding.effect,
            "recommendation": finding.recommendation,
            "evidence": finding.evidence,
        }
        try:
            import json
            result = self.client.generate_json(SYSTEM_PROMPT, json.dumps(payload))
            narrative = result.get("narrative")
            if not narrative or not isinstance(narrative, str):
                return _fallback_narrative(finding)
            return narrative.strip()
        except OllamaUnavailable:
            return _fallback_narrative(finding)

    def narrate_all(self, findings: list[Finding]) -> None:
        for f in findings:
            f.narrative = self.narrate(f)

    def narrate_correlation(self, subject: str, findings: list[Finding]) -> str:
        if not self.available():
            return fallback_correlation_narrative(subject, findings)
        payload = {
            "subject": subject,
            "findings": [
                {
                    "finding_type": f.finding_type.value, "severity": f.severity.value, "system": f.system,
                    "condition": f.condition, "criteria": f.criteria, "cause": f.cause, "effect": f.effect,
                }
                for f in findings
            ],
        }
        try:
            import json
            result = self.client.generate_json(CORRELATION_SYSTEM_PROMPT, json.dumps(payload))
            narrative = result.get("narrative")
            if not narrative or not isinstance(narrative, str):
                return fallback_correlation_narrative(subject, findings)
            return narrative.strip()
        except OllamaUnavailable:
            return fallback_correlation_narrative(subject, findings)

    def narrate_correlations(self, cases: list, findings_by_id: dict) -> None:
        """`cases` are CorrelatedCase objects (correlation.py); sets .narrative
        on each from its own finding_ids, looked up in findings_by_id."""
        for c in cases:
            case_findings = [findings_by_id[fid] for fid in c.finding_ids if fid in findings_by_id]
            c.narrative = self.narrate_correlation(c.subject_label, case_findings)
