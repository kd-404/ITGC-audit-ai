"""Builds a polished, client-ready PDF audit report: cover page, executive
summary, findings sorted by severity (with narrative + evidence citations),
cross-finding correlation ("Auditor Agent") cases, open enquiries, and an
evidence/ingestion appendix.

This is the human-readable deliverable a partner/MD would actually read or
forward - the Excel workpaper (workpaper.py) is the underlying working
papers; this is the report that sits on top of it.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, KeepTogether, HRFlowable,
)

from ..models import Finding, Enquiry

SEVERITY_COLORS = {
    "Critical": colors.HexColor("#C00000"),
    "High": colors.HexColor("#E26B0A"),
    "Medium": colors.HexColor("#B8960C"),
    "Low": colors.HexColor("#6B8E23"),
}
SEVERITY_ORDER = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3}
NAVY = colors.HexColor("#1F4E78")
LIGHT_GREY = colors.HexColor("#F2F2F2")


def _styles():
    ss = getSampleStyleSheet()
    ss.add(ParagraphStyle("ReportTitle", parent=ss["Title"], fontSize=24, textColor=NAVY, spaceAfter=6))
    ss.add(ParagraphStyle("ReportSubtitle", parent=ss["Normal"], fontSize=13, textColor=colors.HexColor("#444444"),
                          alignment=TA_CENTER, spaceAfter=4))
    ss.add(ParagraphStyle("CoverMeta", parent=ss["Normal"], fontSize=10, textColor=colors.HexColor("#666666"),
                          alignment=TA_CENTER))
    ss.add(ParagraphStyle("SectionHeading", parent=ss["Heading1"], fontSize=15, textColor=NAVY,
                          spaceBefore=14, spaceAfter=8, borderPadding=0))
    ss.add(ParagraphStyle("FindingTitle", parent=ss["Heading3"], fontSize=11.5, textColor=colors.black,
                          spaceBefore=10, spaceAfter=2))
    ss.add(ParagraphStyle("Label", parent=ss["Normal"], fontSize=9, textColor=NAVY, fontName="Helvetica-Bold",
                          spaceBefore=4, spaceAfter=1))
    ss.add(ParagraphStyle("Body", parent=ss["Normal"], fontSize=9.5, leading=13))
    ss.add(ParagraphStyle("Citation", parent=ss["Normal"], fontSize=8, fontName="Courier", textColor=colors.HexColor("#555555")))
    ss.add(ParagraphStyle("Narrative", parent=ss["Normal"], fontSize=9.5, leading=13, textColor=colors.HexColor("#1a1a1a"),
                          leftIndent=8, borderLeftWidth=2, borderLeftColor=NAVY, borderPadding=(2, 0, 2, 8)))
    return ss


def _severity_pill(text: str, styles):
    color = SEVERITY_COLORS.get(text, colors.grey)
    style = ParagraphStyle("Pill", parent=styles["Normal"], fontSize=9, fontName="Helvetica-Bold",
                            textColor=colors.white, alignment=TA_CENTER, backColor=color,
                            borderPadding=(3, 6, 3, 6))
    return Paragraph(text.upper(), style)


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#888888"))
    canvas.drawString(0.75 * inch, 0.5 * inch, "Generated by the ITGC Continuous Audit Platform - not a substitute for professional audit judgment")
    canvas.drawRightString(LETTER[0] - 0.75 * inch, 0.5 * inch, f"Page {doc.page}")
    canvas.restoreState()


def _severity_counts(findings: list[Finding]) -> dict:
    counts = {"Critical": 0, "High": 0, "Medium": 0, "Low": 0}
    for f in findings:
        counts[f.severity.value] = counts.get(f.severity.value, 0) + 1
    return counts


def _exec_summary_text(findings: list[Finding], enquiries: list[Enquiry], correlated_cases: list, counts: dict) -> str:
    total = len(findings)
    if total == 0:
        return (
            "No control deviations were identified across the control domains evaluated in this engagement. "
            "This reflects the evidence provided as of the engagement date and does not extend to control "
            "domains or systems outside the scope of this review."
        )
    critical_high = counts.get("Critical", 0) + counts.get("High", 0)
    parts = [
        f"This engagement evaluated the evidence provided and identified {total} finding(s) across the "
        f"control domains in scope, of which {critical_high} are rated Critical or High severity and "
        f"warrant priority remediation."
    ]
    if correlated_cases:
        top = correlated_cases[0]
        parts.append(
            f"{len(correlated_cases)} account(s)/subject(s) were flagged by more than one independently-derived "
            f"control, which increases confidence that those specific gaps are genuine rather than incidental "
            f"- most notably {top.subject_label}, corroborated across {len(top.control_domains)} distinct "
            f"control domain(s)."
        )
    blocking = sum(1 for e in enquiries if e.blocking)
    if blocking:
        parts.append(
            f"{blocking} open enquiry(ies) require a response from the client before certain findings can be "
            f"finalized; see the Open Enquiries section."
        )
    return " ".join(parts)


def build_pdf_report(
    out_path: Path,
    findings: list[Finding],
    enquiries: list[Enquiry],
    correlated_cases: list,
    file_classifications: list[dict],
    engagement_name: str,
    as_of: str,
    llm_status: str = "disabled",
) -> Path:
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    styles = _styles()
    story = []

    counts = _severity_counts(findings)
    sorted_findings = sorted(
        findings, key=lambda f: (SEVERITY_ORDER.get(f.severity.value, 9), f.system, f.subject_person or ""),
    )

    # ---------------------------------------------------------- cover page --
    story.append(Spacer(1, 1.6 * inch))
    story.append(Paragraph("ITGC Continuous Audit Report", styles["ReportTitle"]))
    story.append(Paragraph(engagement_name, styles["ReportSubtitle"]))
    story.append(Spacer(1, 0.3 * inch))
    story.append(Paragraph(f"Engagement date (as of): {as_of}", styles["CoverMeta"]))
    story.append(Paragraph(f"Report generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}", styles["CoverMeta"]))
    story.append(Paragraph(
        f"Narrative source: {'LLM-generated (Ollama)' if llm_status == 'ollama' else 'deterministic fallback template' if 'fallback' in llm_status else llm_status}",
        styles["CoverMeta"],
    ))
    story.append(Spacer(1, 0.5 * inch))

    stat_data = [
        ["Critical", "High", "Medium", "Low", "Total", "Enquiries"],
        [str(counts["Critical"]), str(counts["High"]), str(counts["Medium"]), str(counts["Low"]),
         str(len(findings)), str(len(enquiries))],
    ]
    stat_table = Table(stat_data, colWidths=[0.95 * inch] * 6)
    stat_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BACKGROUND", (0, 1), (-1, 1), LIGHT_GREY),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.white),
    ]))
    story.append(stat_table)
    story.append(PageBreak())

    # ---------------------------------------------------- executive summary --
    story.append(Paragraph("Executive Summary", styles["SectionHeading"]))
    story.append(Paragraph(_exec_summary_text(findings, enquiries, correlated_cases, counts), styles["Body"]))
    story.append(Spacer(1, 0.15 * inch))

    if correlated_cases:
        story.append(Paragraph("Correlated Findings (Multiple Independent Controls Agreeing)", styles["Label"]))
        for c in correlated_cases[:8]:
            story.append(Paragraph(
                f"<b>{c.subject_label}</b> - {c.combined_severity.value} - "
                f"{len(c.finding_ids)} finding(s) across {len(c.control_domains)} domain(s): "
                f"{', '.join(c.control_domains)}",
                styles["Body"],
            ))
            if c.narrative:
                story.append(Paragraph(c.narrative, styles["Narrative"]))
            story.append(Spacer(1, 0.08 * inch))
        story.append(PageBreak())

    # -------------------------------------------------------------- findings --
    story.append(Paragraph("Findings", styles["SectionHeading"]))
    if not sorted_findings:
        story.append(Paragraph("No findings were raised for this engagement.", styles["Body"]))
    for f in sorted_findings:
        block = [
            Table(
                [[Paragraph(f"<b>{f.finding_id}</b> - {f.finding_type.value.replace('_', ' ').title()}",
                            styles["FindingTitle"]),
                  _severity_pill(f.severity.value, styles)]],
                colWidths=[5.1 * inch, 1.0 * inch],
            ),
        ]
        block[0].setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("ALIGN", (1, 0), (1, 0), "RIGHT")]))
        block.append(Paragraph(
            f"System: <b>{f.system}</b> &nbsp;|&nbsp; Subject: <b>{f.subject_person or 'Unidentified / system-level'}</b>"
            + (f" ({f.subject_email})" if f.subject_email else ""),
            styles["Body"],
        ))
        for label, value in [("Condition", f.condition), ("Criteria", f.criteria), ("Cause", f.cause),
                              ("Effect", f.effect), ("Recommendation", f.recommendation)]:
            block.append(Paragraph(label, styles["Label"]))
            block.append(Paragraph(value, styles["Body"]))
        if f.narrative:
            block.append(Paragraph("Auditor Narrative", styles["Label"]))
            block.append(Paragraph(f.narrative, styles["Narrative"]))
        block.append(Paragraph("Evidence", styles["Label"]))
        for cite in f.evidence:
            block.append(Paragraph(cite, styles["Citation"]))
        block.append(Paragraph(f"Confidence: {f.confidence:.0%}", styles["Citation"]))
        block.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CCCCCC"), spaceBefore=8, spaceAfter=4))
        story.append(KeepTogether(block))

    # -------------------------------------------------------- open enquiries --
    if enquiries:
        story.append(PageBreak())
        story.append(Paragraph("Open Enquiries", styles["SectionHeading"]))
        for e in enquiries:
            tag = "BLOCKING" if e.blocking else "Informational"
            story.append(Paragraph(f"<b>{e.enquiry_id}</b> [{tag}] - {e.topic}", styles["FindingTitle"]))
            story.append(Paragraph(e.question, styles["Body"]))
            if e.context:
                story.append(Paragraph(f"Context: {e.context}", styles["Body"]))
            if e.answer:
                story.append(Paragraph(f"Answer: {e.answer}", styles["Body"]))
            story.append(Spacer(1, 0.1 * inch))

    # ------------------------------------------------------ evidence appendix --
    if file_classifications:
        story.append(PageBreak())
        story.append(Paragraph("Appendix: Evidence Ingested", styles["SectionHeading"]))
        data = [["File", "Evidence Type", "Confidence"]]
        for c in file_classifications:
            data.append([c["file"], c["evidence_type"], f"{c['confidence']:.0%}"])
        t = Table(data, colWidths=[3.4 * inch, 2.0 * inch, 0.9 * inch], repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), NAVY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT_GREY]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DDDDDD")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(t)

    doc = SimpleDocTemplate(
        str(out_path), pagesize=LETTER,
        topMargin=0.75 * inch, bottomMargin=0.75 * inch, leftMargin=0.75 * inch, rightMargin=0.75 * inch,
        title=engagement_name, author="ITGC Continuous Audit Platform",
    )
    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return out_path
